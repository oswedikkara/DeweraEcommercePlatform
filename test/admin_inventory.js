const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const items = new Map();
const session = new Map([['dewera_staff_role','super_admin'],['dewera_staff_token','test-token']]);
let response;
const calls=[];
const context = vm.createContext({console, sessionStorage:{getItem:k=>session.get(k),removeItem:k=>session.delete(k)},localStorage:{getItem:k=>items.get(k),setItem:(k,v)=>items.set(k,v)},fetch:async(url,options)=>{calls.push({url,options});return response;},setTimeout:()=>0,document:{},window:{},URL,Blob});
vm.runInContext(fs.readFileSync('admin/admin.js','utf8'),context);
const seed={id:'test-stone',sellerId:'dewera',isDewera:true,name:'Test Sapphire',status:'available'};
vm.runInContext('rememberInventory('+JSON.stringify([seed])+')',context);
(async()=>{
 response={ok:false,json:async()=>({success:false,error:'Save rejected'})};
 await assert.rejects(vm.runInContext("updateGemStatus('test-stone','sold')",context),/Save rejected/);
 assert.equal(JSON.parse(vm.runInContext('JSON.stringify(getGems())',context))[0].status,'available');
 assert.equal(calls[0].url,'/api/gems/update');
 assert.equal(JSON.parse(calls[0].options.body).id,'test-stone');
 response={ok:true,json:async()=>({success:true,gem:{...seed,status:'sold'}})};
 await vm.runInContext("updateGemStatus('test-stone','sold')",context);
 assert.equal(JSON.parse(vm.runInContext('JSON.stringify(getGems())',context))[0].status,'sold');
 response={ok:false,json:async()=>({success:false,error:'Delete rejected'})};
 await assert.rejects(vm.runInContext("deleteGem('test-stone')",context),/Delete rejected/);
 assert.equal(vm.runInContext('getGems().length',context),1);
 response={ok:true,json:async()=>({success:true})};
 await vm.runInContext("deleteGem('test-stone')",context);
 assert.equal(vm.runInContext('getGems().length',context),0);
 response={ok:true,json:async()=>({success:true,gem:seed})};
 await vm.runInContext("addGem({name:'Test Sapphire'})",context);
 assert.equal(calls.at(-1).url,'/api/gems');
 assert.equal(Array.isArray(JSON.parse(calls.at(-1).options.body)),false);
 assert.equal(JSON.parse(calls.at(-1).options.body).isDewera,true);
 console.log('Admin inventory persistence checks passed; no business records changed.');
})().catch(error=>{console.error(error);process.exitCode=1;});
